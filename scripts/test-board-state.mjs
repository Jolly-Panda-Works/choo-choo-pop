import assert from 'node:assert/strict';
import { getLevel } from '../src/game/levels.js';
import { hydrateLevel } from '../src/game/levels.js';
import { edgeAllowed, initialPaths, stepOnto, evaluate } from '../src/game/logic.js';
import { solveStats } from '../src/game/solver.js';
import { boardSignature, freshBoard, restoreDraft, pushBoard, undoBoard, redoBoard } from '../src/game/boardState.js';
const level=getLevel(81);
let h={past:[],present:freshBoard(level),future:[]};
const first=h.present;
const li=1, cell=level.lanes[li].solution[1];
h=pushBoard(h,{paths:stepOnto(level,h.present.paths,li,cell),notes:{}});
const second=h.present;
h=pushBoard(h,{...h.present,notes:{0:2}});
assert.deepEqual(undoBoard(h).present,second);
assert.deepEqual(undoBoard(undoBoard(h)).present,first);
assert.deepEqual(redoBoard(undoBoard(h)).present,h.present);
assert.equal(pushBoard(undoBoard(h),{...second,notes:{1:1}}).future.length,0);
const draft=JSON.parse(JSON.stringify({...h,signature:boardSignature(level),hintsUsed:2}));
assert.deepEqual(restoreDraft(level,draft).present,h.present);
assert.equal(restoreDraft(getLevel(82),draft),null);
assert.equal(restoreDraft(level,{...draft,present:{paths:[[999]],notes:{}}}),null);
const raw={rows:3,cols:3,entry:[1,0,3],exit:[1,2,1],solution:[3,4,5],given:[],difficulty:1};
const wall=hydrateLevel({...raw,walls:[[3,4]]});
assert.equal(edgeAllowed(wall,3,4),false);
assert.equal(edgeAllowed(wall,4,3),false);
const start=initialPaths(wall);
assert.equal(stepOnto(wall,start,0,4),start);
assert.equal(evaluate(wall,[[3,4,5]]).solved,false);
assert.equal(solveStats(wall,2).found,0);
const fixed=hydrateLevel({...raw,fixed:[{cell:4,sides:[0,2]}]});
assert.equal(stepOnto(fixed,initialPaths(fixed),0,4)[0].length,1);
assert.equal(evaluate(fixed,[[3,4,5]]).solved,false);
assert.equal(solveStats(fixed,2).found,0);
assert.equal(solveStats(hydrateLevel({...raw,fixed:[{cell:4,sides:[1,3]}]}),2).found,1);
assert.ok(getLevel(61).fixed.length);
assert.ok(getLevel(71).walls.length);
assert.equal(getLevel(61).lesson,'fixedLesson');
assert.equal(getLevel(71).lesson,'wallLesson');
console.log('History, drafts, wall boundaries and fixed rail directions OK');
