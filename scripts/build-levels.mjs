// Deterministic campaign builder. Five coached puzzles followed by short, easy
// single-track puzzles in lands 1-3; lands 4-6 introduce powers and extra trains.
import { writeFileSync } from 'node:fs';
import { mulberry32 } from '../src/game/rng.js';
import { generateCandidate, generateMulti } from '../src/game/generator.js';
import { hydrateLevel } from '../src/game/levels.js';
import { LEVEL_DATA as OLD } from '../src/game/levelData.js';
import { dirBetween } from '../src/game/logic.js';
import { puzzleKey } from './puzzle-key.mjs';
import { solveStats } from '../src/game/solver.js';

const out = OLD.slice(0, 5);
const fingerprints = new Set(out.map(puzzleKey));
for (let n = 6; n <= 120; n++) {
  const stage = Math.ceil(n / 20);
  const slot = (n - 1) % 20;
  const easy = stage <= 3;
  const rows = easy ? 3 : stage === 4 ? 4 : 5;
  const cols = easy ? (n > 20 ? 4 : 3) : stage === 4 ? 4 : 5;
  const trains = stage <= 4 ? 1 : stage === 5 ? 2 : slot < 10 ? 2 : 3;
  const cap = easy ? 24 : stage === 4 ? 120 : stage === 5 ? 400 : 1000;
  const rng = mulberry32(20261108 + n * 131);
  let accepted = false;
  for (let attempt = 0; attempt < 30000; attempt++) {
    let d;
    if (trains === 1) {
      const c = generateCandidate(rows, cols, easy ? 0.34 + slot % 3 * 0.05 : 0.48 + slot / 160, rng);
      if (!c || (easy && c.solution.length > 6)) continue;
      d = { rows, cols, entry: c.entry, exit: c.exit, solution: c.solution, given: [], difficulty: 1 };
    } else {
      const c = generateMulti(rows, cols, trains, 0.52 + slot / 200, rng, 0);
      if (!c) continue;
      d = { ...c, given: [], difficulty: stage === 6 && slot >= 10 ? 2 : 1 };
    }
    if (n >= 61) {
      const lanes = d.lanes || [{solution:d.solution}];
      d.fixed = lanes.slice(0, n>=101 ? 2 : 1).map(l => {
        const j=Math.max(1,Math.floor(l.solution.length/2));
        return {cell:l.solution[j],sides:[dirBetween(d,l.solution[j],l.solution[j-1]),dirBetween(d,l.solution[j],l.solution[j+1])]};
      });
      if(n===61) d.lesson='fixedLesson';
      if(n>=71) {
        const used=new Set(lanes.flatMap(l=>l.solution.slice(1).map((b,j)=>[l.solution[j],b].sort((a,b)=>a-b).join(':'))));
        const blocks=new Set(d.blocks||[]); const pool=[];
        for(let a=0;a<rows*cols;a++) for(const b of [a+1,a+cols]) {
          if(b>=rows*cols || dirBetween(d,a,b)<0 || blocks.has(a)||blocks.has(b)||used.has([a,b].join(':'))) continue;
          pool.push([a,b]);
        }
        d.walls=pool.slice(slot%Math.max(1,pool.length),slot%Math.max(1,pool.length)+(n>=101?3:2));
        if(!d.walls.length) continue;
        if(n===71) d.lesson='wallLesson';
      }
    }
    const fingerprint = puzzleKey(d);
    if (fingerprints.has(fingerprint)) continue;
    const st = solveStats(hydrateLevel(d), 2, cap + 1);
    if (st.capped || st.found !== 1 || st.nodes > cap) continue;
    fingerprints.add(fingerprint);
    out.push({ ...d, nodes: st.nodes });
    accepted = true;
    break;
  }
  if (!accepted) throw new Error(`Could not build level ${n}`);
  console.log(`level ${n}: ${rows}x${cols}, trains=${trains}, nodes=${out.at(-1).nodes}`);
}
writeFileSync(new URL('../src/game/levelData.js', import.meta.url),
  '// Generated by scripts/build-levels.mjs — every puzzle has exactly one solution.\nexport const LEVEL_DATA = ' + JSON.stringify(out) + ';\n');
console.log(`Built ${out.length} campaign puzzles.`);
